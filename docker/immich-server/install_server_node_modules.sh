#!/usr/bin/env bash
set -euo pipefail
export LC_ALL=C

cd /immich-npm
sha256sum -c TREE.sha256
server=/usr/src/app/server
old="$server/node_modules"
staged=$(mktemp -d "$server/.npm-update.XXXXXXXX")
tar --extract --gzip --file=node_modules.tar.gz --directory="$staged" \
    --no-same-owner --no-same-permissions
new="$staged/node_modules"
test -d "$new/.pnpm"
chmod -R a+rX -- "$new"
test "$(node --version)" = v24.22.1

package_path() {
    local root="$1" package="$2" resolved
    resolved=$(realpath -e -- "$root/$package")
    [[ "$resolved" == "$root/"* && -f "$resolved/package.json" ]]
    printf '%s\n' "$resolved"
}

old_sharp=$(package_path "$old" sharp)
new_sharp=$(package_path "$new" sharp)
old_sdk=$(package_path "$old" @immich/plugin-sdk)
new_sdk=$(package_path "$new" @immich/plugin-sdk)
bcrypt=$(package_path "$new" bcrypt)
exiftool=$(package_path "$new" exiftool-vendored.pl)
sharp_binary=src/build/Release/sharp-linux-x64-0.35.5.node
printf '%s  %s\n' \
    'b291e2a1f0bd27d747b4799efb73a139e6ab670ad96fce8b789da8bc6c288bf2' "$old_sharp/$sharp_binary" \
    'd640649833b5f0504096b747ae1a66e0780291edc5c33b541696b2cf2aabb5e3' "$bcrypt/prebuilds/linux-x64/bcrypt.glibc.node" \
    '16592a69eb014ab416a80a3df89e7ed7100f94e7261f6c7110c9a0c8b4d55318' "$new_sdk/package.json" \
    '0779d059d458628cb4ab06c3e7d2a7e5b5e40698fce230c5aa0908bbb844f40b' "$old_sdk/plugin-sdk.mjs" \
    '7894328add69a1fe0a44f7d8c84cd527efeafb9bc6dc01b3b0280d236f010861' "$server/dist/main.js" \
    | sha256sum -c -
test "$(node -p 'require(process.argv[1]).version' "$new_sharp/package.json")" = 0.35.5
test "$(perl "$exiftool/bin/exiftool" -ver)" = 13.59
(
    cd "$old_sdk"
    sha256sum -c /immich-npm/SDK.sha256
    test "$(find dist -type f | wc -l)" -eq 7
)
install -D -m 0755 -- "$old_sharp/$sharp_binary" "$new_sharp/$sharp_binary"
install -m 0755 -- "$old_sdk/plugin-sdk.mjs" "$new_sdk/plugin-sdk.mjs"
test ! -L "$new_sdk/dist"
install -d -m 0755 -- "$new_sdk/dist"
cp -R --no-preserve=ownership -- "$old_sdk/dist/." "$new_sdk/dist/"
(
    cd "$new_sdk"
    sha256sum -c /immich-npm/SDK.sha256
)
linked=$(ldd "$new_sharp/$sharp_binary")
[[ "$linked" == *libvips* && "$linked" != *'not found'* ]]

rm -rf -- "$old"
mv -- "$new" "$old"
node - "$old" <<'JS'
const assert = require('node:assert/strict');
const path = process.argv[2];
const sharp = require(path + '/sharp');
const bcrypt = require(path + '/bcrypt');
assert.equal(sharp.versions.sharp, '0.35.5');
assert.equal(sharp.versions.vips, '8.18.7');
assert.ok(bcrypt.compareSync('fixture', bcrypt.hashSync('fixture', 4)));
JS
node --check "$server/dist/main.js"
(cd "$server" && node --input-type=module -e 'await import("@immich/plugin-sdk")')
rm -rf -- "$staged"
