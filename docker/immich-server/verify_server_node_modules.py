"""Check the standalone Immich 3.3.6 Node dependency tree before packaging."""

import argparse
import hashlib
import json
import os
import stat
from pathlib import Path

GRAPH_SHA = "4ed180eaec133dc9cf55bafe159121d2484bed14d5b2af03a830baa6a5889ccd"
BCRYPT_SHA = "d640649833b5f0504096b747ae1a66e0780291edc5c33b541696b2cf2aabb5e3"
REQUIRED = {
    ("@immich/plugin-sdk", "0.0.0"),
    ("bcrypt", "6.0.0"),
    ("exiftool-vendored.pl", "13.59.0"),
    ("handlebars", "4.7.10"),
    ("proxy-addr", "2.0.8"),
    ("sharp", "0.35.5"),
    ("tar", "7.5.21"),
}


def manifest(path):
    package = json.loads(path.read_bytes())
    return package["name"], package["version"]


def verify(root, graph):
    physical = set()
    links = 0
    for directory, subdirs, names in os.walk(root, followlinks=False):
        folder = Path(directory)
        for name in [*subdirs, *names]:
            path = folder / name
            mode = path.lstat().st_mode
            if stat.S_ISLNK(mode):
                if Path(os.readlink(path)).is_absolute() or not path.resolve(
                    strict=True
                ).is_relative_to(root):
                    raise ValueError(f"Enlace fuera del árbol: {path.relative_to(root)}")
                links += 1
            elif not (stat.S_ISREG(mode) or stat.S_ISDIR(mode)):
                raise ValueError(f"Entrada especial: {path.relative_to(root)}")
            if (
                name == "package.json"
                and stat.S_ISREG(mode)
                and (
                    folder.parent.name == "node_modules"
                    or (
                        folder.parent.name.startswith("@")
                        and folder.parent.parent.name == "node_modules"
                    )
                )
            ):
                physical.add(manifest(path))
    closure = {(package["name"], package["version"]) for package in graph["server"]["packages"]}
    workspace_sdk = ("@immich/plugin-sdk", "0.0.0")
    unexpected = physical - closure - {workspace_sdk}
    missing = REQUIRED - physical
    if unexpected or missing:
        raise ValueError(
            f"Fuera del grafo: {sorted(unexpected)}. Requeridos ausentes: {sorted(missing)}"
        )
    for name, version in (
        workspace_sdk,
        ("bcrypt", "6.0.0"),
        ("sharp", "0.35.5"),
        ("exiftool-vendored.pl", "13.59.0"),
    ):
        if manifest(root / name / "package.json") != (name, version):
            raise ValueError(f"Resolución directa inesperada: {name}")
    bcrypt = root / "bcrypt/prebuilds/linux-x64/bcrypt.glibc.node"
    if hashlib.sha256(bcrypt.read_bytes()).hexdigest() != BCRYPT_SHA:
        raise ValueError("SHA inesperado para bcrypt glibc")
    if not (root / "exiftool-vendored.pl/bin/exiftool").is_file():
        raise ValueError("Falta el binario Perl de ExifTool")
    return {
        "links": links,
        "identities": sorted(physical),
        "frozen_graph_omitted": sorted(closure - physical),
        "graph_sha256": GRAPH_SHA,
        "success": True,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("node_modules", type=Path)
    parser.add_argument("graph", type=Path)
    args = parser.parse_args()
    root = args.node_modules.resolve(strict=True)
    if root.name != "node_modules" or not (root / ".pnpm").is_dir():
        parser.error("Se requiere el directorio node_modules del deploy")
    graph_raw = args.graph.read_bytes()
    if hashlib.sha256(graph_raw).hexdigest() != GRAPH_SHA:
        parser.error("Grafo congelado inesperado")
    print(json.dumps(verify(root, json.loads(graph_raw)), sort_keys=True))


if __name__ == "__main__":
    main()
