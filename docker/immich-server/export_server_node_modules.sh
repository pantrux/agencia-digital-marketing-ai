#!/bin/sh
set -eu
umask 077

seed=/work/private/immich-js-seed-v1
replay="$seed/supplement-prettier-v1"
workspace="$replay/workspace"
store="$seed/store"
tool="$seed/tool/package/bin/pnpm.mjs"
node=/usr/bin/node
output="${1:?Indica un directorio absoluto nuevo para el deploy}"
metadata="${2:?Indica el archivo de espejos npm}"
case "$output" in
    "$seed"|"$seed/"*|*/) exit 1 ;;
    /work/*) ;;
    *) exit 1 ;;
esac
test "$(uname -m)" = x86_64
test "$(printf '%s\n' /sys/class/net/*)" = /sys/class/net/lo
"$node" --version >/dev/null
/usr/bin/python3.12 -I - "$output" <<'PY'
import os
import sys
from pathlib import Path

raw_path = sys.argv[1]
path = Path(raw_path)
if str(path.resolve()) != raw_path or os.path.lexists(path):
    sys.exit("El directorio de salida debe ser nuevo y absoluto")
if not os.confstr("CS_GNU_LIBC_VERSION").startswith("glibc "):
    sys.exit("El SDK requiere glibc")
PY

check_inputs() {
    printf '%s  %s\n' \
        'c9f0030334c1d8f0d84e57ce49ce5afe1381126b14065f279e7e369248e04bb0' "$node" \
        'ff3224d46b47fbb24a7e9fe15fededef7e00892d07d4e376b6762d4899906bfd' "$tool" \
        '53a7d8390b4a8bed15c3b51abb98084c2753e2614d39f9a24eca91b28ce73a4b' "$workspace/pnpm-lock.yaml" \
        '66b974d6498744f8379c60844949a9fdb0cccd6985d721c50f26cbdd8f154078' "$workspace/pnpm-workspace.yaml" \
        'a5211bf11486b1b046f0a4948d9f059f3329041bf5918fee9c9369978b084c7d' "$workspace/server/package.json" \
        '13db7bbdf684b3ad9b0cdcac41220b4bcf3b422c46c305921d418d6504b9d08d' "$store/v11/index.db" \
        | sha256sum -c -
}

check_inputs
mkdir -- "$output"
for directory in home path tmp cache/pnpm config state data; do
    mkdir -p -- "$output/$directory"
done
touch -- "$output/empty.npmrc"
policy="$replay/replay-env/cache/pnpm/lockfile-verified.jsonl"
exported_policy="$output/cache/pnpm/lockfile-verified.jsonl"
/usr/bin/python3.12 -I - "$policy" "$workspace" "$exported_policy" <<'PY'
import json
import sys
from pathlib import Path

source, workspace, target = map(Path, sys.argv[1:])
expected_path = str(workspace / "pnpm-lock.yaml")
raw = source.read_bytes()
for row in map(json.loads, raw.splitlines()):
    lock = row["lockfile"]
    if (
        lock["path"] == expected_path
        and lock["hash"] == "uFI3ZknioFkm4cec+AqKP0wdO2JVLawdyzU2JpXDJ44="
        and row["policy"]["minimumReleaseAge"] == 1440
    ):
        target.write_bytes(raw)
        break
else:
    sys.exit("No se encontró el recibo de política del lock congelado")
PY

printf '%s  %s\n' \
    '5936efa42bfbc0fe2b2f181ad1805187d6e5e33b48c79f2f5edf55a35ef1f3dc' "$metadata" \
    | sha256sum -c -
mkdir -- "$output/cache/pnpm/v11"
tar -xzf "$metadata" -C "$output/cache/pnpm/v11"
(
    cd "$output/cache/pnpm/v11"
    printf '%s  METADATA.sha256\n' '521d695a1dcfe4cc2e09bed95edb533d1a941d26c83b5712c39ec6509924f023' \
        | sha256sum -c -
    sha256sum -c METADATA.sha256 >"$output/metadata-check.log"
)

code=0
env -i HOME="$output/home" PATH="$output/path" TMPDIR="$output/tmp" CI=true LC_ALL=C.UTF-8 \
    XDG_CACHE_HOME="$output/cache" XDG_CONFIG_HOME="$output/config" \
    XDG_STATE_HOME="$output/state" XDG_DATA_HOME="$output/data" PNPM_HOME="$output/home" \
    NPM_CONFIG_USERCONFIG="$output/empty.npmrc" NPM_CONFIG_GLOBALCONFIG="$output/empty.npmrc" \
    "$node" "$tool" --dir "$workspace" --filter immich deploy --prod --no-optional \
    --offline --frozen-lockfile --registry https://registry.npmjs.org/ \
    --config.ignore-scripts=true --config.ignore-pnpmfile=true \
    --config.manage-package-manager-versions=false --config.verify-store-integrity=true \
    --config.frozen-store=true --config.package-import-method=copy --reporter=append-only \
    --store-dir "$store" "$output/deploy" >"$output/deploy.log" 2>&1 || code=$?
cat -- "$output/deploy.log"
check_inputs
test "$code" -eq 0
test -d "$output/deploy/node_modules/.pnpm"
